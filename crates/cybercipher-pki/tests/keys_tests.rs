#[test]
fn keygen_2048_material_and_oaep_roundtrip() {
    let keypair = gen(2048);
    let m = keypair.material();

    // Modulus size and default exponent.
    assert_eq!(keypair.bits(), 2048);
    assert_eq!(m.e, DEFAULT_EXPONENT_HEX);
    assert_eq!(m.e, "010001");
    // Hex transport: even-length lowercase hex, n is 2048 bits = 512 nibbles.
    assert_eq!(m.n.len(), 512);
    assert!(m.n.bytes().all(|b| b.is_ascii_hexdigit()));
    // All eight components present and distinct where they must be.
    for (name, value) in [
        ("n", &m.n),
        ("e", &m.e),
        ("d", &m.d),
        ("p", &m.p),
        ("q", &m.q),
        ("dp", &m.dp),
        ("dq", &m.dq),
        ("qinv", &m.qinv),
    ] {
        assert!(!value.is_empty(), "{name} missing");
    }
    assert_ne!(m.p, m.q, "p and q must differ");

    // Sanity: the rsa crate's own OAEP survives one encrypt/decrypt round
    // using the key material this crate produced.
    let plaintext = b"cybercipher oaep sanity";
    let private = keypair.rsa_private_key();
    let public = keypair.rsa_public_key();
    let ciphertext = public
        .encrypt(&mut rand::rngs::OsRng, Oaep::new::<Sha256>(), plaintext)
        .expect("OAEP encrypt");
    let recovered = private
        .decrypt(Oaep::new::<Sha256>(), &ciphertext)
        .expect("OAEP decrypt");
    assert_eq!(recovered, plaintext);

    // PKCS#8 PEM round-trip: serialize, re-parse, all fields must match.
    let pkcs8_pem = keypair.to_pkcs8_pem().expect("pkcs8 pem");
    assert!(pkcs8_pem.starts_with("-----BEGIN PRIVATE KEY-----"));
    let reparsed = match parse_pem(&pkcs8_pem).expect("re-parse pkcs8") {
        ParsedKey::Private { keypair, format } => {
            assert_eq!(format, KeyFormat::Pkcs8);
            keypair
        }
        _ => panic!("expected a private key"),
    };
    assert_eq!(reparsed.material(), m);
    assert_eq!(reparsed.bits(), 2048);
}

