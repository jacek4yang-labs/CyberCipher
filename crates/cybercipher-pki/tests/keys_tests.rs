#[test]
fn jwk_roundtrip_key_to_json_and_back() {
    let keypair = gen(2048);
    let m = keypair.material();

    let jwk = keypair_to_jwk(&keypair);
    assert_eq!(jwk.kty, "RSA");
    // Private JWK carries the full parameter set.
    assert!(jwk.d.is_some() && jwk.p.is_some() && jwk.q.is_some());
    assert!(jwk.dp.is_some() && jwk.dq.is_some() && jwk.qi.is_some());
    // base64url without padding.
    assert!(!jwk.n.contains('=') && !jwk.n.contains('+') && !jwk.n.contains('/'));

    let json = jwk_to_json(&jwk).unwrap();
    let parsed = parse_jwk(&json).unwrap();
    assert_eq!(parsed, jwk);

    let back = jwk_to_keypair(&parsed).unwrap();
    assert_eq!(back.material(), m);

    // Public-only direction.
    let public_jwk = public_material_to_jwk(&keypair.public_material());
    assert!(public_jwk.d.is_none());
    let public_back = jwk_to_public_material(&public_jwk).unwrap();
    assert_eq!(public_back, keypair.public_material());
}

#[test]
fn jwk_with_missing_crt_params_still_loads() {
    // RFC 7518 section 6.3.2: dp/dq/qi are optional. Start from a full JWK,
    // strip the CRT parameters, and the key must still reconstruct.
    let keypair = gen(2048);
    let mut jwk = keypair_to_jwk(&keypair);
    jwk.dp = None;
    jwk.dq = None;
    jwk.qi = None;
    let back = jwk_to_keypair(&jwk).unwrap();
    let m = back.material();
    // n/e/d/p/q preserved; dp/dq/qinv re-derived identically.
    assert_eq!(m.n, keypair.material().n);
    assert_eq!(m.d, keypair.material().d);
    assert_eq!(m.dp, keypair.material().dp);
    assert_eq!(m.qinv, keypair.material().qinv);
}

#[test]
fn jwk_errors_are_typed() {
    // Wrong kty: the kty check fires before any parameter decoding, so an
    // EC-typed JWK with empty parameters still gets the typed error.
    let ec_jwk = RsaJwk {
        kty: "EC".to_string(),
        n: String::new(),
        e: String::new(),
        d: None,
        p: None,
        q: None,
        dp: None,
        dq: None,
        qi: None,
        kid: None,
    };
    let err = jwk_to_public_material(&ec_jwk).unwrap_err();
    assert_eq!(err.kind, ErrorKind::Unsupported);
    assert!(err.message.contains("kty"), "message: {}", err.message);

    // Bad base64url in n.
    let keypair = gen(2048);
    let mut jwk = keypair_to_jwk(&keypair);
    jwk.n = "%%%".to_string();
    let err = jwk_to_keypair(&jwk).unwrap_err();
    assert_kind(&err, ErrorKind::Decode);
    assert_eq!(err.parameter.as_deref(), Some("n"));

    // Public JWK used where a private key is needed.
    let public_jwk = public_material_to_jwk(&keypair.public_material());
    let err = jwk_to_keypair(&public_jwk).unwrap_err();
    assert_eq!(err.kind, ErrorKind::InvalidInput);

    // Private JWK without p/q: not supported yet (no factoring).
    let mut private_no_p = keypair_to_jwk(&keypair);
    private_no_p.p = None;
    private_no_p.q = None;
    let err = jwk_to_keypair(&private_no_p).unwrap_err();
    assert_eq!(err.kind, ErrorKind::Unsupported);
    assert!(
        err.message.contains("not supported yet"),
        "message: {}",
        err.message
    );

    // Invalid JSON.
    let err = parse_jwk("{not json").unwrap_err();
    assert_kind(&err, ErrorKind::Decode);
}

#[test]
fn jwks_parse_object_and_bare_array() {
    let keypair = gen(2048);
    let jwk = keypair_to_jwk(&keypair);
    let json = jwk_to_json(&jwk).unwrap();

    // RFC 7517 section 5 object form.
    let jwks = format!(r#"{{"keys": [{json}]}}"#);
    let keys = parse_jwks(&jwks).unwrap();
    assert_eq!(keys.len(), 1);
    assert_eq!(keys[0], jwk);

    // Bare array form.
    let bare = format!("[{json}]");
    let keys = parse_jwks(&bare).unwrap();
    assert_eq!(keys.len(), 1);

    // Round-trip through jwks_to_json.
    let serialized = jwks_to_json(&keys).unwrap();
    assert_eq!(parse_jwks(&serialized).unwrap(), keys);

    // Neither form -> typed decode error.
    let err = parse_jwks("{\"nope\": []}").unwrap_err();
    assert_kind(&err, ErrorKind::Decode);
}

#[test]
fn jwk_inspection_reports_jwk_format_and_hex() {
    let keypair = gen(2048);
    let jwk = keypair_to_jwk(&keypair);
    let inspection = jwk.inspect().unwrap();
    assert_eq!(inspection.format, KeyFormat::Jwk);
    assert_eq!(inspection.key_type, KeyType::RsaPrivate);
    assert_eq!(inspection.bit_length, 2048);
    assert_eq!(inspection.n, keypair.material().n);
    assert!(inspection.qinv.is_some());

    let public = public_material_to_jwk(&keypair.public_material());
    let inspection = public.inspect().unwrap();
    assert_eq!(inspection.key_type, KeyType::RsaPublic);
    assert!(inspection.d.is_none());
}

