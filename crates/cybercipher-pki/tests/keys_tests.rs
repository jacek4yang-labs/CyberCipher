#[test]
fn unsupported_algorithm_oid_is_typed() {
    // A well-formed PKCS#8 PrivateKeyInfo carrying an EC key OID
    // (id-ecPublicKey 1.2.840.10045.2.1) instead of rsaEncryption.
    let ec_pkcs8: &[u8] = &[
        0x30, 0x10, // SEQUENCE (16 content bytes)
        0x02, 0x01, 0x00, // version INTEGER 0
        0x30, 0x09, // AlgorithmIdentifier SEQUENCE (9 content bytes, no params)
        0x06, 0x07, 0x2a, 0x86, 0x48, 0xce, 0x3d, 0x02, 0x01, // OID ecPublicKey
        0x04, 0x00, // privateKey OCTET STRING (empty)
    ];
    let err = parse_pkcs8_private_der(ec_pkcs8).unwrap_err();
    assert_kind(&err, ErrorKind::Unsupported);
    assert!(
        err.message.contains("rsaEncryption"),
        "message: {}",
        err.message
    );

    // SPKI carrying the same non-RSA OID.
    let ec_spki: &[u8] = &[
        0x30, 0x0f, // SEQUENCE (15 bytes)
        0x30, 0x09, // AlgorithmIdentifier SEQUENCE (9 bytes)
        0x06, 0x07, 0x2a, 0x86, 0x48, 0xce, 0x3d, 0x02, 0x01, // OID ecPublicKey
        0x03, 0x02, 0x00, 0xaa, // subjectPublicKey BIT STRING
    ];
    let err = parse_spki_public_der(ec_spki).unwrap_err();
    assert_kind(&err, ErrorKind::Unsupported);
}

