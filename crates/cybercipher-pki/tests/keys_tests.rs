#[test]
fn all_four_pem_headers_parse_with_correct_format() {
    let keypair = gen(2048);

    let cases = [
        (
            keypair.to_public_spki_pem().unwrap(),
            KeyFormat::Spki,
            KeyType::RsaPublic,
        ),
        (
            keypair.to_public_pkcs1_pem().unwrap(),
            KeyFormat::Pkcs1,
            KeyType::RsaPublic,
        ),
        (
            keypair.to_pkcs8_pem().unwrap(),
            KeyFormat::Pkcs8,
            KeyType::RsaPrivate,
        ),
        (
            keypair.to_pkcs1_pem().unwrap(),
            KeyFormat::Pkcs1,
            KeyType::RsaPrivate,
        ),
    ];
    for (pem, format, key_type) in cases {
        let inspection = inspect_pem(&pem).expect("parse should succeed");
        assert_eq!(inspection.format, format, "pem: {pem}");
        assert_eq!(inspection.key_type, key_type);
    }

    // Public PEMs parse to public material whose n/e match the keypair.
    let public_pem = keypair.to_public_spki_pem().unwrap();
    match parse_pem(&public_pem).expect("parse public") {
        ParsedKey::Public { material, format } => {
            assert_eq!(format, KeyFormat::Spki);
            assert_eq!(material, keypair.public_material());
        }
        _ => panic!("expected a public key"),
    }
}

#[test]
fn serialize_every_direction_from_a_parsed_key() {
    let original = gen(2048);
    // Parse once from PKCS#8 and regenerate all four PEM forms from the
    // parsed key; each must parse again with identical material.
    let pkcs8_pem = original.to_pkcs8_pem().unwrap();
    let parsed = match parse_pem(&pkcs8_pem).unwrap() {
        ParsedKey::Private { keypair, .. } => keypair,
        _ => panic!("expected private"),
    };
    let m = original.material();

    for pem in [
        parsed.to_pkcs8_pem().unwrap(),
        parsed.to_pkcs1_pem().unwrap(),
        parsed.to_public_spki_pem().unwrap(),
        parsed.to_public_pkcs1_pem().unwrap(),
    ] {
        let inspection = inspect_pem(&pem).unwrap();
        assert_eq!(inspection.n, m.n);
        assert_eq!(inspection.e, m.e);
    }

    // Same for a public-only key: both public PEM forms.
    let public_pem = original.to_public_spki_pem().unwrap();
    match parse_pem(&public_pem).unwrap() {
        ParsedKey::Public { material, .. } => {
            // Re-serialization is deterministic: identical PEM.
            assert_eq!(material.to_spki_pem().unwrap(), public_pem);
            assert!(material
                .to_pkcs1_pem()
                .unwrap()
                .starts_with("-----BEGIN RSA PUBLIC KEY-----"));
        }
        _ => panic!("expected public"),
    }
}

#[test]
fn certificate_pem_is_a_typed_wrong_object_type_error() {
    // Valid base64 body so only the label classification is exercised.
    let pem = pem_with_body("CERTIFICATE", "MIIB");
    let err = parse_pem(&pem).unwrap_err();
    assert_kind(&err, ErrorKind::InvalidInput);
    assert!(
        err.message.contains("wrong PEM object type"),
        "message: {}",
        err.message
    );
    assert_eq!(err.actual.as_deref(), Some("CERTIFICATE"));
    assert!(err
        .details
        .as_deref()
        .unwrap_or_default()
        .contains("certificate"));

    // Same classification for CSRs and CRLs.
    for label in ["CERTIFICATE REQUEST", "X509 CRL"] {
        let err = parse_pem(&pem_with_body(label, "MIIB")).unwrap_err();
        assert_kind(&err, ErrorKind::InvalidInput);
    }
}

#[test]
fn garbage_pem_body_is_a_typed_decode_error() {
    // Valid armor, valid base64, invalid DER.
    let pem = pem_with_body("PUBLIC KEY", "AAAA");
    let err = parse_pem(&pem).unwrap_err();
    assert_kind(&err, ErrorKind::Decode);
    assert!(
        err.message.contains("invalid DER"),
        "message: {}",
        err.message
    );
    assert!(err.details.is_some(), "DER parser detail expected");

    // Valid armor, non-base64 body.
    let pem = pem_with_body("RSA PRIVATE KEY", "!!! not base64 !!!");
    let err = parse_pem(&pem).unwrap_err();
    assert_kind(&err, ErrorKind::Decode);

    // Completely missing armor.
    let err = parse_pem("just some text").unwrap_err();
    assert_kind(&err, ErrorKind::Decode);

    // Missing END marker.
    let pem = "-----BEGIN PUBLIC KEY-----\nAAAA\n";
    let err = parse_pem(pem).unwrap_err();
    assert_kind(&err, ErrorKind::Decode);

    // Empty input.
    let err = parse_pem("   \n  ").unwrap_err();
    assert_kind(&err, ErrorKind::Decode);
}

