#[test]
fn keygen_rejects_unsupported_bit_lengths() {
    // Below the floor.
    let err = generate_rsa_keypair(100, DEFAULT_EXPONENT_HEX).unwrap_err();
    assert_kind(&err, ErrorKind::InvalidParam);
    assert_eq!(err.parameter.as_deref(), Some("bits"));

    // Above the cap — the error points at the cap and at the attack tooling.
    let err = generate_rsa_keypair(8192, DEFAULT_EXPONENT_HEX).unwrap_err();
    assert_kind(&err, ErrorKind::InvalidParam);
    assert!(err.message.contains("4096"), "message: {}", err.message);
    assert!(err
        .details
        .as_deref()
        .unwrap_or_default()
        .contains("attack"));

    // In-between sizes are rejected too (not silently rounded).
    for bits in [1500usize, 2049, 3] {
        let err = generate_rsa_keypair(bits, DEFAULT_EXPONENT_HEX).unwrap_err();
        assert_kind(&err, ErrorKind::InvalidParam);
    }
}

#[test]
fn keygen_rejects_bad_exponents() {
    // Not hex.
    let err = generate_rsa_keypair(2048, "zzzz").unwrap_err();
    assert_kind(&err, ErrorKind::Decode);
    assert_eq!(err.parameter.as_deref(), Some("e"));

    // Even exponent.
    let err = generate_rsa_keypair(2048, "010000").unwrap_err();
    assert_kind(&err, ErrorKind::InvalidParam);
    assert!(err.message.contains("odd"), "message: {}", err.message);

    // Too small (1 and 2).
    for e in ["01", "02"] {
        let err = generate_rsa_keypair(2048, e).unwrap_err();
        assert_kind(&err, ErrorKind::InvalidParam);
        assert!(err.message.contains(">= 3"), "message: {}", err.message);
    }
}

