#[test]
fn der_roundtrip_all_four_structures() {
    let keypair = gen(2048);
    let m = keypair.material();
    let pub_m = keypair.public_material();

    // Private: PKCS#1 and PKCS#8.
    let pkcs1 = keypair.to_pkcs1_der().unwrap();
    assert_eq!(parse_pkcs1_private_der(&pkcs1).unwrap().material(), m);
    let pkcs8 = keypair.to_pkcs8_der().unwrap();
    assert_eq!(parse_pkcs8_private_der(&pkcs8).unwrap().material(), m);

    // Public: PKCS#1 and SPKI.
    let pub_pkcs1 = keypair.to_public_pkcs1_der().unwrap();
    assert_eq!(parse_pkcs1_public_der(&pub_pkcs1).unwrap(), pub_m);
    let spki = keypair.to_public_spki_der().unwrap();
    assert_eq!(parse_spki_public_der(&spki).unwrap(), pub_m);

    // inspect_der sniffs each structure and reports its format.
    assert_eq!(inspect_der(&pkcs8).unwrap().format, KeyFormat::Pkcs8);
    assert_eq!(inspect_der(&pkcs1).unwrap().format, KeyFormat::Pkcs1);
    assert_eq!(inspect_der(&spki).unwrap().format, KeyFormat::Spki);
    assert_eq!(inspect_der(&pub_pkcs1).unwrap().format, KeyFormat::Pkcs1);

    // Garbage DER is a typed decode error, not a panic.
    let err = inspect_der(&[0x00, 0x01, 0x02, 0x03]).unwrap_err();
    assert_kind(&err, ErrorKind::Decode);
}

