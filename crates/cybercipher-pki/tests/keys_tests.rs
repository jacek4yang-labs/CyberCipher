fn gen(bits: usize) -> RsaKeypair {
    generate_rsa_keypair(bits, DEFAULT_EXPONENT_HEX).expect("keygen should succeed")
}

/// A syntactically valid PEM block with a valid-base64 but meaningless body.
fn pem_with_body(label: &str, body: &str) -> String {
    format!("-----BEGIN {label}-----\n{body}\n-----END {label}-----\n")
}

fn assert_kind(err: &OperationError, kind: ErrorKind) {
    assert_eq!(err.kind, kind, "unexpected error: {err}");
}

