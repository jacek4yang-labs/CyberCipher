#[test]
fn inspection_serializes_snake_case_with_private_fields() {
    let keypair = gen(2048);
    let inspection = keypair.inspect().unwrap();
    let json = serde_json::to_string(&inspection).unwrap();
    assert!(
        json.contains("\"key_type\":\"rsa_private\""),
        "json: {json}"
    );
    assert!(json.contains("\"bit_length\":2048"), "json: {json}");
    assert!(json.contains("\"qinv\""), "json: {json}");
    assert!(json.contains("\"summary\""), "json: {json}");

    // Public inspection omits private fields entirely.
    let public = keypair.public_material();
    let json = serde_json::to_string(&public.inspect().unwrap()).unwrap();
    assert!(
        !json.contains("\"d\""),
        "public inspection must omit d: {json}"
    );
}

#[test]
fn key_material_serializes_as_flat_hex_object() {
    let keypair = gen(2048);
    let json = serde_json::to_string(&keypair.material()).unwrap();
    for field in ["n", "e", "d", "p", "q", "dp", "dq", "qinv"] {
        assert!(
            json.contains(&format!("\"{field}\"")),
            "missing {field}: {json}"
        );
    }
    // Values are hex strings, not numbers.
    let value: serde_json::Value = serde_json::from_str(&json).unwrap();
    assert!(value["n"].is_string());
}
